import { META_BY_CATEGORY } from "../lib/generated/metaIndex";
import { SEARCH_BY_CATEGORY } from "../lib/generated/searchIndex";
import { articleBasePath } from "./categoriesData";

export interface ArticleListing {
  title: string;
  slug: string;
  description: string;
  tags: string[];
}

export interface ArticleChunks {
  slug: string;
  chunks: { text: string; headingId: string; headingText: string }[];
}

/**
 * Every category's generated meta + full-text chunks, assembled from the two
 * registry indexes. Imported by the search worker AND the regression check
 * (scripts/check-search.ts) so both see the same 13-category corpus - the
 * check used to load only 5 and drifted silently.
 *
 * NEVER import the searchIndex half from a component: it pulls ~1.4 MB of
 * article text into whatever bundle references it.
 *
 * The generated files are regenerated by `npm run generate:meta` (part of
 * `build`); while `npm run dev` runs, the devMetaWatcher vite plugin keeps
 * them in step with the .mdx content automatically.
 */
export const ARTICLE_SOURCES: ReadonlyArray<{
  meta: readonly ArticleListing[];
  search: readonly ArticleChunks[];
  categoryId: string;
  basePath: string;
}> = Object.keys(SEARCH_BY_CATEGORY).map((categoryId) => ({
  meta: META_BY_CATEGORY[categoryId] ?? [],
  search: SEARCH_BY_CATEGORY[categoryId],
  categoryId,
  basePath: articleBasePath(categoryId),
}));
